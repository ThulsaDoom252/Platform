/**
 * Чистка выгрузки Google Docs.
 *
 * Экспорт документа в HTML тащит внутри себя все картинки, закодированные
 * прямо в текст, поэтому у конспекта с десятком скриншотов выгрузка легко
 * весит десятки мегабайт. Для дерева папок из неё нужны только заголовки.
 */

/** Выкидывает то, что в дереве не нужно, но весит больше всего. */
export function stripHeavy(html: string): string {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, "")
    .replace(/<img\b[^>]*>/gi, "")
    .replace(/\s(?:src|href|xlink:href)="data:[^"]*"/gi, "");
}

/**
 * Оставляет от документа одни заголовки.
 *
 * Уровень вложенности живёт в самом теге (h1, h2, h3), поэтому такой
 * огрызок разбирается ровно так же, как целый документ, — а весит
 * килобайты вместо мегабайтов. Возвращает null, если заголовков нет:
 * тогда вложенность придётся искать в списках, а для этого нужна вся
 * разметка.
 */
export function headingsOnly(html: string): string | null {
  const found = [...html.matchAll(/<h([1-6])\b[^>]*>([\s\S]*?)<\/h\1>/gi)];
  if (found.length < 2) return null;

  return found.map(([, level, inner]) => `<h${level}>${inner}</h${level}>`).join("\n");
}
