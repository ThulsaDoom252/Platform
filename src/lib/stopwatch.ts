/**
 * Секундомер ответа.
 *
 * Время меряется от того момента, когда вопрос показали, — не от
 * рендера компонента и не от старта всего задания. Поэтому часы
 * заводятся отдельным вызовом из эффекта, а не при создании: рендер
 * может повториться, а вопрос при этом не меняется.
 *
 * Пока часы не заведены, они честно отдают ноль, а не время с начала
 * эпохи.
 */
export type Stopwatch = {
  /** Завести (или перевести) часы на «сейчас». */
  start: () => void;
  /** Сколько прошло с последнего start/lap. */
  ms: () => number;
  /** То же, но заодно начинает отсчёт заново — для серии ответов. */
  lap: () => number;
};

export function stopwatch(): Stopwatch {
  let from = 0;

  return {
    start() {
      from = Date.now();
    },
    ms() {
      return from ? Date.now() - from : 0;
    },
    lap() {
      const now = Date.now();
      const spent = from ? now - from : 0;
      from = now;
      return spent;
    },
  };
}
