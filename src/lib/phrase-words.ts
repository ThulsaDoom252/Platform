/**
 * Сколько в записи слов и нужна ли ей транскрипция.
 *
 * Слову транскрипция помогает, выражению — нет: читать её целиком никто
 * не станет, а места она занимает столько же, сколько сама фраза.
 * Поэтому она остаётся там, где действительно нужна — у одного слова,
 * произношение которого неочевидно.
 *
 * Считает только форму записи, поэтому живёт отдельно от разметки и
 * проверяется тестами: ошибиться здесь легко, а заметить трудно.
 */

/**
 * Пометки, которые словом не считаются.
 *
 * Артикль — «a fork» это то же одно слово. Инфинитивное «to» — тоже:
 * «to fade» в словнике значит глагол fade, а не выражение из двух слов,
 * и транскрипция ему нужна ровно так же.
 */
const MARKERS = new Set(["a", "an", "the", "to"]);

/**
 * Сколько в записи значимых слов.
 *
 * Скобки и их содержимое отбрасываются: «on the left (side)» — это
 * пояснение к выражению, а не его часть.
 */
export function wordCount(phrase: string): number {
  return String(phrase ?? "")
    .toLowerCase()
    .replace(/\([^)]*\)/g, " ")
    // «weed / weeds» и «close-knit / tight-knit» — одно слово с
    // вариантом написания, а не два разных.
    .split("/")[0]
    // Дефис и апостроф внутри слова его не разрывают: «well-known» и
    // «don't» — по одному слову.
    .replace(/[^a-zЀ-ӿ'’-]+/gi, " ")
    .split(" ")
    .map((word) => word.replace(/^['’-]+|['’-]+$/g, ""))
    .filter(Boolean)
    .filter((word) => !MARKERS.has(word)).length;
}

/** Показывать ли транскрипцию к этой записи. */
export function hasTranscription(phrase: string): boolean {
  return wordCount(phrase) === 1;
}
